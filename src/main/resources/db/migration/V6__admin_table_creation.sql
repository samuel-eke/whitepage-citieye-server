-- ✅ Reuses functions and enums already defined in V1__initial_db_setup.sql:
--    · auth.nigerian_state       — enum for Nigerian states
--    · auth.gender_type          — enum for gender values
--    · auth.user_role            — enum for system roles
--    · auth.compute_user_citizen_code() — trigger function that generates role-aware citizen codes
--      (cit-fo-XX-XXXXXX for field_officer, cit-adm-XXXXXX for agency_admin,
--       cit-super-XXXXXX for super_admin)


CREATE TABLE IF NOT EXISTS auth.admin_user (id BIGSERIAL PRIMARY KEY,
                                                         first_name VARCHAR(100) NOT NULL,
                                                                                 middle_name VARCHAR(100),
                                                                                             last_name VARCHAR(100) NOT NULL, -- Enforces exactly 11 digits starting with 0 (same constraint as users_auth)
 phone_number VARCHAR(11) UNIQUE NOT NULL CHECK (phone_number ~ '^0[0-9]{10}$'), email VARCHAR(255) UNIQUE NOT NULL CHECK (email ~* '^[A-Za-z0-9._%-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,4}$'), -- Uses the same nigerian_state enum from V1 so state codes are consistent
 state_of_origin auth.nigerian_state NOT NULL,
                                     state_of_residence auth.nigerian_state NOT NULL, -- Uses the gender_type enum from V1
 gender auth.gender_type NOT NULL, -- Enforces exactly 11 digits (same as users_auth)
 nin VARCHAR(11) UNIQUE NOT NULL CHECK (nin ~ '^[0-9]{11}$'), address TEXT NOT NULL, -- Uses the shared user_role enum; only admin-level roles are permitted here
 role auth.user_role NOT NULL CHECK (role IN ('field_officer',
                                              'agency_admin',
                                              'super_admin')), -- Minimum password length of 8 characters (same constraint as users_auth)
 password VARCHAR(255) NOT NULL CHECK (char_length(password) >= 8), -- Auto-generated by the reused compute_user_citizen_code() trigger
 citizen_code VARCHAR(30) UNIQUE,
                          created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
                                                                                        updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL);

-- =========================================================================
-- 2. BIND THE EXISTING CITIZEN-CODE TRIGGER TO THIS TABLE
--    auth.compute_user_citizen_code() was defined in V1 and already handles:
--    · field_officer  → 'cit-fo-{state_of_residence_code}-{6 alphanumeric}'
--    · agency_admin   → 'cit-adm-{6 numeric}'
--    · super_admin    → 'cit-super-{6 numeric}'
-- =========================================================================

DROP TRIGGER IF EXISTS trigger_auto_compute_citizen_code ON auth.admin_user;


CREATE TRIGGER trigger_auto_compute_citizen_code
BEFORE
INSERT ON auth.admin_user
FOR EACH ROW EXECUTE FUNCTION auth.compute_user_citizen_code();

-- =========================================================================
-- 3. PERFORMANCE INDEXES
-- =========================================================================

CREATE INDEX idx_admin_user_email_lower ON auth.admin_user (LOWER(email));


CREATE INDEX idx_admin_user_role ON auth.admin_user (role);


CREATE INDEX idx_admin_user_state_origin ON auth.admin_user (state_of_origin);